using Content.Client.UserInterface.Controls;
using Content.Shared.Botany;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.Botany.UI;

/// <summary>
/// Lists the seed piles stored in a seed extractor, with their stats and genes.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class SeedExtractorWindow : FancyWindow
{
    [Dependency] private IEntityManager _entMan = default!;

    public event Action<string>? OnTake;
    public event Action<string>? OnScrap;

    private SeedExtractorState? _state;

    public SeedExtractorWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        SearchBar.OnTextChanged += _ => Populate();
    }

    public void UpdateState(SeedExtractorState state)
    {
        _state = state;
        CapacityLabel.Text = Loc.GetString("seed-extractor-capacity", ("stored", state.Stored), ("capacity", state.Capacity));
        Populate();
    }

    private void Populate()
    {
        PileList.RemoveAllChildren();
        if (_state == null)
            return;

        if (_state.Piles.Count == 0)
        {
            PileList.AddChild(new Label { Text = Loc.GetString("seed-extractor-empty"), FontColorOverride = Color.Gray });
            return;
        }

        var filter = SearchBar.Text.Trim();
        var sprite = _entMan.System<SpriteSystem>();
        foreach (var pile in _state.Piles)
        {
            if (filter.Length > 0 && !Matches(pile, filter))
                continue;

            PileList.AddChild(MakeRow(pile, sprite));
            PileList.AddChild(new Control { MinHeight = 6 });
        }
    }

    private static bool Matches(SeedExtractorPileEntry pile, string filter)
    {
        bool Has(string s) => s.Contains(filter, StringComparison.OrdinalIgnoreCase);
        if (Has(pile.Name))
            return true;

        foreach (var s in pile.Traits)
        {
            if (Has(s))
                return true;
        }

        foreach (var s in pile.Chemicals)
        {
            if (Has(s))
                return true;
        }

        return false;
    }

    private Control MakeRow(SeedExtractorPileEntry pile, SpriteSystem sprite)
    {
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true };

        var icon = new TextureRect
        {
            MinSize = new Vector2i(32, 32),
            Stretch = TextureRect.StretchMode.KeepCentered,
            TextureScale = new System.Numerics.Vector2(1, 1),
            VerticalAlignment = VAlignment.Top,
        };
        if (pile.SeedRsi != null)
            icon.Texture = sprite.Frame0(new SpriteSpecifier.Rsi(new ResPath(pile.SeedRsi), "seed"));
        row.AddChild(icon);

        var info = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true, Margin = new Thickness(6, 0, 0, 0) };
        info.AddChild(new Label
        {
            Text = Loc.GetString("seed-extractor-pile-name", ("name", pile.Name), ("amount", pile.Amount)),
            StyleClasses = { "LabelKeyText" },
            ClipText = true,
        });
        info.AddChild(new Label
        {
            Text = Loc.GetString("seed-extractor-pile-stats",
                ("potency", Fmt(pile.Potency)),
                ("yield", Fmt(pile.Yield)),
                ("production", Fmt(pile.Production)),
                ("endurance", Fmt(pile.Endurance)),
                ("lifespan", Fmt(pile.Lifespan)),
                ("maturation", Fmt(pile.Maturation))),
            FontColorOverride = Color.LightGray,
        });

        if (pile.Traits.Count > 0)
            info.AddChild(Wrapped(Loc.GetString("seed-extractor-pile-traits", ("traits", string.Join(", ", pile.Traits)))));
        if (pile.Chemicals.Count > 0)
            info.AddChild(Wrapped(Loc.GetString("seed-extractor-pile-chemicals", ("chemicals", string.Join(", ", pile.Chemicals)))));
        if (pile.Mutations.Count > 0)
            info.AddChild(Wrapped(Loc.GetString("seed-extractor-pile-mutations", ("mutations", string.Join(", ", pile.Mutations)))));
        row.AddChild(info);

        var buttons = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, VerticalAlignment = VAlignment.Top };
        var take = new Button { Text = Loc.GetString("seed-extractor-take-button") };
        var key = pile.Key;
        take.OnPressed += _ => OnTake?.Invoke(key);
        buttons.AddChild(take);

        var scrap = new ConfirmButton
        {
            Text = Loc.GetString("seed-extractor-scrap-button"),
            ConfirmationText = Loc.GetString("seed-extractor-scrap-confirm"),
            Margin = new Thickness(0, 4, 0, 0),
        };
        scrap.OnPressed += _ => OnScrap?.Invoke(key);
        buttons.AddChild(scrap);
        row.AddChild(buttons);

        return row;
    }

    private static Control Wrapped(string text)
    {
        var label = new RichTextLabel { HorizontalExpand = true };
        label.SetMessage(FormattedMessage.FromUnformatted(text));
        return label;
    }

    private static string Fmt(float value) => Content.Shared.Botany.Systems.SharedBotanySystem.FormatStat(value);
}
