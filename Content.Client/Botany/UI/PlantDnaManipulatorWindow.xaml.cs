using Content.Client.UserInterface.Controls;
using Content.Shared.Botany;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Botany.UI;

[GenerateTypedNameReferences]
public sealed partial class PlantDnaManipulatorWindow : FancyWindow
{
    public event Action? OnEjectSeed;
    public event Action? OnEjectDisk;
    public event Action? OnInsert;
    public event Action<PlantGeneKind, int>? OnExtract;
    public event Action<PlantGeneKind, int>? OnRemove;
    public event Action<int>? OnReplace;

    public PlantDnaManipulatorWindow()
    {
        RobustXamlLoader.Load(this);
        EjectSeedButton.OnPressed += _ => OnEjectSeed?.Invoke();
        EjectDiskButton.OnPressed += _ => OnEjectDisk?.Invoke();
        InsertButton.OnPressed += _ => OnInsert?.Invoke();
    }

    public void UpdateState(PlantDnaManipulatorState state)
    {
        SeedLabel.Text = state.SeedName ?? Loc.GetString("plant-dna-no-sample");
        EjectSeedButton.Disabled = state.SeedName == null;

        DiskLabel.Text = !state.HasDisk
            ? Loc.GetString("plant-dna-no-disk")
            : state.DiskReadOnly
                ? Loc.GetString("plant-dna-disk-readonly", ("name", state.DiskName ?? string.Empty))
                : state.DiskName ?? string.Empty;
        EjectDiskButton.Disabled = !state.HasDisk;

        InsertButton.Visible = state.CanInsert;
        InsertButton.Text = state.InsertLabel ?? string.Empty;

        GeneList.RemoveAllChildren();
        if (state.SeedName == null)
        {
            GeneList.AddChild(new Label { Text = Loc.GetString("plant-dna-insert-sample") });
            return;
        }

        AddSection(state, PlantGeneKind.Core, "plant-dna-core-genes", null);
        AddSection(state, PlantGeneKind.Chemical, "plant-dna-chemical-genes", "plant-dna-no-chemical-genes");
        AddSection(state, PlantGeneKind.Trait, "plant-dna-trait-genes", "plant-dna-no-trait-genes");
    }

    private void AddSection(PlantDnaManipulatorState state, PlantGeneKind kind, string header, string? empty)
    {
        GeneList.AddChild(new Label { Text = Loc.GetString(header), StyleClasses = { "LabelKeyText" }, Margin = new Thickness(0, 6, 0, 2) });

        var any = false;
        foreach (var gene in state.Genes)
        {
            if (gene.Kind != kind)
                continue;

            any = true;
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true };
            row.AddChild(new Label { Text = gene.Name, HorizontalExpand = true, ClipText = true });

            if (gene.CanExtract)
            {
                var extract = new ConfirmButton
                {
                    Text = Loc.GetString("plant-dna-extract"),
                    ConfirmationText = Loc.GetString("plant-dna-extract-confirm"),
                    ToolTip = gene.ExtractWarning != null
                        ? Loc.GetString("plant-dna-extract-tooltip-degrade", ("warning", gene.ExtractWarning))
                        : Loc.GetString("plant-dna-extract-tooltip"),
                };
                var (k, i) = (gene.Kind, gene.Index);
                extract.OnPressed += _ => OnExtract?.Invoke(k, i);
                row.AddChild(extract);
            }

            if (gene.CanReplace)
            {
                var replace = new ConfirmButton
                {
                    Text = Loc.GetString("plant-dna-replace"),
                    ConfirmationText = Loc.GetString("plant-dna-confirm"),
                };
                var i = gene.Index;
                replace.OnPressed += _ => OnReplace?.Invoke(i);
                row.AddChild(replace);
            }

            if (gene.CanRemove)
            {
                var remove = new ConfirmButton
                {
                    Text = Loc.GetString("plant-dna-remove"),
                    ConfirmationText = Loc.GetString("plant-dna-confirm"),
                };
                var (k, i) = (gene.Kind, gene.Index);
                remove.OnPressed += _ => OnRemove?.Invoke(k, i);
                row.AddChild(remove);
            }

            GeneList.AddChild(row);
        }

        if (!any && empty != null)
            GeneList.AddChild(new Label { Text = Loc.GetString(empty), FontColorOverride = Color.Gray });
    }
}
