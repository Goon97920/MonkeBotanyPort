using Content.Client.Message;
using Content.Client.UserInterface.Controls;
using Content.Shared.Botany;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Botany.UI;

[GenerateTypedNameReferences]
public sealed partial class PlantSplicerWindow : FancyWindow
{
    public event Action? OnEjectFirst;
    public event Action? OnEjectSecond;
    public event Action? OnEjectBeaker;
    public event Action? OnSplice;
    public event Action? OnInfuse;

    public PlantSplicerWindow()
    {
        RobustXamlLoader.Load(this);
        EjectFirstButton.OnPressed += _ => OnEjectFirst?.Invoke();
        EjectSecondButton.OnPressed += _ => OnEjectSecond?.Invoke();
        EjectBeakerButton.OnPressed += _ => OnEjectBeaker?.Invoke();
        SpliceButton.OnPressed += _ => OnSplice?.Invoke();
        InfuseButton.OnPressed += _ => OnInfuse?.Invoke();
    }

    public void UpdateState(PlantSplicerState state)
    {
        FirstSeedLabel.Text = state.FirstSeed ?? Loc.GetString("plant-splicer-empty-slot");
        FirstSeedStats.SetMarkup(state.FirstSeedStats ?? string.Empty);
        EjectFirstButton.Disabled = state.FirstSeed == null;

        SecondSeedLabel.Text = state.SecondSeed ?? Loc.GetString("plant-splicer-empty-slot");
        SecondSeedStats.SetMarkup(state.SecondSeedStats ?? string.Empty);
        EjectSecondButton.Disabled = state.SecondSeed == null;

        BeakerContents.SetMarkup(state.Beaker ?? Loc.GetString("plant-splicer-no-beaker"));
        EjectBeakerButton.Disabled = state.Beaker == null;

        DamageLabel.SetMarkup(state.FirstSeed == null
            ? string.Empty
            : Loc.GetString("plant-splicer-damage",
                ("current", MathF.Round(state.InfusionDamage, 1)),
                ("added", MathF.Round(state.PotentialDamage, 1)),
                ("total", MathF.Round(state.InfusionDamage + state.PotentialDamage, 1))));

        SpliceButton.Disabled = state.FirstSeed == null || state.SecondSeed == null;
        InfuseButton.Disabled = state.FirstSeed == null || state.Beaker == null;
    }
}
